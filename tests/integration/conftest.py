class LoginFlow:
    """Drives HA's login flow the way the frontend and the Companion app do."""

    def __init__(self, session: aiohttp.ClientSession, base_url: str) -> None:
        self.session = session
        self.base = base_url
        self.client_id = f"{base_url}/"

    async def start(self) -> dict:
        async with self.session.post(
            f"{self.base}/auth/login_flow",
            json={"client_id": self.client_id, "handler": ["homeassistant", None], "redirect_uri": self.client_id},
        ) as resp:
            assert resp.status == 200, await resp.text()
            return await resp.json()

    async def step(self, flow_id: str, data: dict) -> dict:
        """One flow step. A 403 (login blocked or refused) is returned as {"status": 403, ...}."""
        async with self.session.post(
            f"{self.base}/auth/login_flow/{flow_id}", json={"client_id": self.client_id, **data}
        ) as resp:
            assert resp.status in (200, 403), await resp.text()
            body = await resp.json()
            return {"status": 403, **body} if resp.status == 403 else body

    async def token(self, code: str) -> dict:
        async with self.session.post(
            f"{self.base}/auth/token",
            data={"grant_type": "authorization_code", "code": code, "client_id": self.client_id},
        ) as resp:
            assert resp.status == 200, await resp.text()
            return await resp.json()

    async def login(self, username: str, password: str, totp_secret: str | None = None) -> dict:
        flow = await self.start()
        result = await self.step(flow["flow_id"], {"username": username, "password": password})
        if result.get("step_id") == "select_mfa_module":
            result = await self.step(flow["flow_id"], {"multi_factor_auth_module": "totp"})
        if result.get("step_id") == "mfa" and totp_secret:
            result = await self.step(flow["flow_id"], {"code": totp(totp_secret)})
        return result


async def create_user(ha: HA, name: str, password: str) -> str:
    user = await ha.call({"type": "config/auth/create", "name": name, "group_ids": ["system-users"], "local_only": False})
    user_id = user["user"]["id"]
    await ha.call(
        {"type": "config/auth_provider/homeassistant/create", "user_id": user_id, "username": name, "password": password}
    )
    return user_id


async def enable_totp(session: aiohttp.ClientSession, username: str, password: str) -> str:
    """Log in locally as the user and enrol TOTP, returning the secret."""
    flow = LoginFlow(session, LOCAL_URL)
    result = await flow.login(username, password)
    access_token = (await flow.token(result["result"]))["access_token"]

    async with session.ws_connect(f"{LOCAL_URL.replace('http', 'ws', 1)}/api/websocket") as ws:
        await ws.receive_json()
        await ws.send_json({"type": "auth", "access_token": access_token})
        await ws.receive_json()
        await ws.send_json({"id": 1, "type": "auth/setup_mfa", "mfa_module_id": "totp"})
        step = (await ws.receive_json())["result"]
        secret = step["description_placeholders"]["code"]
        await ws.send_json({"id": 2, "type": "auth/setup_mfa", "flow_id": step["flow_id"], "user_input": {"code": totp(secret)}})
        done = await ws.receive_json()
        assert done["result"]["type"] == "create_entry", done
    return secret


