def totp(secret: str, at: float | None = None) -> str:
    """RFC 6238 code, as generated by an authenticator app."""
    key = base64.b32decode(secret.upper() + "=" * (-len(secret) % 8))
    counter = struct.pack(">Q", int((at or time.time()) // 30))
    digest = hmac.new(key, counter, hashlib.sha1).digest()
    offset = digest[-1] & 0x0F
    return f"{(struct.unpack('>I', digest[offset:offset + 4])[0] & 0x7FFFFFFF) % 1_000_000:06d}"


class VMResolver(AbstractResolver):
    """Resolves every hostname to the test VM, like a DNS record would."""

    async def resolve(self, host, port=0, family=socket.AF_INET):
        return [{"hostname": host, "host": VM_HOST, "port": port, "family": family, "proto": 0, "flags": 0}]

    async def close(self):
        pass


class Panel:
    """Talks to the AirBound panel through HA ingress, the way the sidebar page does."""

    def __init__(self, session: aiohttp.ClientSession, base: str) -> None:
        self.session = session
        self.base = base

    async def get(self, path: str):
        async with self.session.get(f"{self.base}{path}") as resp:
            assert resp.status == 200, f"{path}: {resp.status} {await resp.text()}"
            return await resp.json()

    async def post(self, path: str, body: dict | None = None, expect: int = 200):
        async with self.session.post(f"{self.base}{path}", json=body or {}) as resp:
            assert resp.status == expect, f"{path}: {resp.status} {await resp.text()}"
            return await resp.json()


async def ingress() -> tuple[str, str]:
    """(panel base URL, ingress session cookie) for the token's user."""
    async with HA() as ha:
        info = await ha.supervisor("/addons/local_airbound/info")
        me = await ha.call({"type": "auth/current_user"})
        session = await ha.supervisor("/ingress/session", "post", {"user_id": me["id"]})
    return f"{LOCAL_URL}{info['ingress_url']}", session["session"]


